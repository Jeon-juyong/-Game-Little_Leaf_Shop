export function generateDailyCustomers(day) {
  // 날마다 다른 시드로 안정적인 셔플
  function seededRandom(seed) {
    const x = Math.sin(seed) * 10000;
    return x - Math.floor(x);
  }

  const sorted = [...CUSTOMER_POOL]
    .map((c, i) => ({ ...c, _sort: seededRandom(day * 31 + i * 7 + 17) }))
    .sort((a, b) => a._sort - b._sort)
    .map(({ _sort, ...c }) => c);

  return sorted.slice(0, 3).map(c => ({ ...c, served: false }));
}
