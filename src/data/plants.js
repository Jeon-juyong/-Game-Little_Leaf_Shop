export function getPlantById(id) {
  return PLANTS.find(p => p.id === id);
}

export function calcMatchScore(customerNeeds, plantKeywords) {
  if (!customerNeeds?.length || !plantKeywords?.length) return 0;
  const matched = customerNeeds.filter(need => plantKeywords.includes(need));
  return Math.round((matched.length / customerNeeds.length) * 100);
}
